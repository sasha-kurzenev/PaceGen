// Reproducible, one-time asset import. App playback never uses these URLs.
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { Buffer } from 'node:buffer';
const commit = '22d222ce36e290ba3792c776811aa9c69dcc8776';
const base = `https://raw.githubusercontent.com/octalmusic/octal-samples/${commit}/`;
const selection = {
  kickDance: 'house.kick.punch-03', kickHouse: 'house.kick.sub-03', kickTechno: 'house.kick.punch-01',
  clap: 'house.clap.classic-02', snare: 'house.snare.body-01',
  closedHat: 'house.hat.closed-01', softHat: 'house.hat.closed-09',
  openHat: 'house.hat.open-01', shaker: 'house.perc.shaker-01',
};
async function download(path) {
  const response = await fetch(base + path);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}
await mkdir('assets/audio', { recursive: true });
const manifest = JSON.parse((await download('manifest.json')).toString());
if (manifest.license !== 'CC0-1.0') throw new Error('Unexpected license');
const embedded = {}, provenance = [];
for (const [name, id] of Object.entries(selection)) {
  const item = manifest.samples[id];
  const data = await download(item.path);
  if (data.toString('ascii', 0, 4) !== 'RIFF' || data.toString('ascii', 8, 12) !== 'WAVE') throw new Error('Not WAV');
  await writeFile(`assets/audio/${name}.wav`, data);
  embedded[name] = data.toString('base64');
  provenance.push({ name, id, url: base + item.path, sha256: createHash('sha256').update(data).digest('hex'), bytes: data.length, ...item });
}
await writeFile('assets/audio/LICENSE-CC0.txt', await download('LICENSE'));
await writeFile('assets/audio/UPSTREAM-LICENSES.md', await download('LICENSES.md'));
await writeFile('assets/audio/provenance.json', JSON.stringify({ commit, license: manifest.license, samples: provenance }, null, 2) + '\n');
await writeFile('src/drumSamples.js', '// Generated by scripts/import-drums.mjs. CC0; see assets/audio/provenance.json.\nexport const drumSamples = ' + JSON.stringify(embedded) + ';\n');
await writeFile('src/drumSamples.d.ts', 'export const drumSamples: Record<string, string>;\n');
console.log(`Embedded ${provenance.length} samples, ${provenance.reduce((sum, item) => sum + item.bytes, 0)} WAV bytes`);
