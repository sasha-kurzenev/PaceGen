"""Embed the selected CC0 FreePats guitar bank for offline WebView playback."""

import base64
import io
import json
from pathlib import Path
import sys
import wave

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "experiments/guitar-spike"))
from render import SAMPLES, sfz_regions, RATE  # noqa: E402


def short_wav(path, seconds=0.9):
    with wave.open(str(path), "rb") as original:
        if original.getframerate() != RATE or original.getsampwidth() != 2:
            raise ValueError(f"Unexpected WAV format: {path}")
        frames = original.readframes(round(seconds * RATE))
        with io.BytesIO() as data:
            with wave.open(data, "wb") as output:
                output.setnchannels(original.getnchannels())
                output.setsampwidth(2)
                output.setframerate(RATE)
                output.writeframes(frames)
            return base64.b64encode(data.getvalue()).decode("ascii")


def main():
    regions = []
    for region in sfz_regions(next(SAMPLES.glob("*.sfz"))):
        if region["high"] < 41 or region["low"] > 79:
            continue
        regions.append({"low": region["low"], "high": region["high"],
                        "center": region["center"], "wav": short_wav(region["file"])})
    output = ROOT / "src/music/rockSampleBank.ts"
    output.write_text("// Generated by scripts/import-rock-guitar.py. FreePats CC0; see experiments/guitar-spike/README.md.\n"
                      "export const rockSampleBank = " + json.dumps(regions, separators=(",", ":")) + " as const;\n",
                      encoding="utf-8")
    print(f"{len(regions)} regions, {output.stat().st_size} bytes in {output}")


if __name__ == "__main__":
    main()
